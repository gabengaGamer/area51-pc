anim_key* base_player::GetMixBuffer( mix_buffer MixBuffer )
{
    // Use main memory
    static anim_key s_MixBuffer[MAX_ANIM_BONES * MIX_BUFFER_COUNT];
    return &s_MixBuffer[MAX_ANIM_BONES * MixBuffer];
}
